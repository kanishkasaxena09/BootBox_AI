export const applyTranslation = async (text, direction, toneId) => {
  if (!text.trim()) return '';

  try {
    const res = await fetch('/api/corporate/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, direction, tone: toneId }),
    });
    if (res.ok) {
      const data = await res.json();
      if (!data.fallback && data.translated) return data.translated;
    }
  } catch (e) {
    console.warn('AI translation failed, using mock:', e.message);
  }

  const dict = direction === 'simpleToCorporate' ? simpleToCorporate : corporateToSimple;
  const tone = dict[toneId] || dict.formal;
  let result = text;

  tone.phrases.forEach(([pattern, replacement]) => {
    result = result.replace(pattern, replacement);
  });

  const words = result.split(/(\s+|[.,!?;:])/);
  const translated = words.map(word => {
    if (/^\s+$/.test(word) || /^[.,!?;:]$/.test(word)) return word;
    const lower = word.toLowerCase();
    if (tone.wordMap[lower]) {
      const replacement = tone.wordMap[lower];
      if (word[0] === word[0].toUpperCase() && word[0] !== word[0].toLowerCase()) {
        return replacement.charAt(0).toUpperCase() + replacement.slice(1);
      }
      return replacement;
    }
    return word;
  });

  return translated.join('');
};
